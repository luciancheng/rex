// Package skill holds the rex-plan agent skill, embedded so the binary
// can install it. It is installed only on an explicit
// `rex ingest --install-skill`, so nothing joins an agent's context unasked.
package skill

import (
	"bytes"
	_ "embed"
	"fmt"
	"io"
	"os"
	"path/filepath"
)

//go:embed rex-plan/SKILL.md
var RexPlan []byte

const marker = "<!-- generated by rex"

// Dir is where the skill goes: ~/.claude/skills/rex-plan, or the repo's
// .claude/skills/rex-plan with project. Claude Code reads both; OpenCode
// reads the global one.
func Dir(home, repo string, project bool) string {
	if project {
		return filepath.Join(repo, ".claude", "skills", "rex-plan")
	}
	if dir := os.Getenv("CLAUDE_CONFIG_DIR"); dir != "" {
		return filepath.Join(dir, "skills", "rex-plan")
	}
	return filepath.Join(home, ".claude", "skills", "rex-plan")
}

// Install writes SKILL.md into dir. A SKILL.md that Rex didn't write is
// left alone.
func Install(dir string, out io.Writer) error {
	path := filepath.Join(dir, "SKILL.md")
	if have, err := os.ReadFile(path); err == nil {
		if !bytes.Contains(have, []byte(marker)) {
			return fmt.Errorf("%s exists and Rex didn't write it; move it to install the rex-plan skill", path)
		}
		if bytes.Equal(have, RexPlan) {
			fmt.Fprintf(out, "rex-plan skill already installed at %s\n", path)
			return nil
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".SKILL.md.rex-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(RexPlan); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return err
	}
	fmt.Fprintf(out, "installed the rex-plan skill at %s\n", path)
	return nil
}

// Uninstall removes Rex's SKILL.md and the folder if that leaves it empty.
func Uninstall(dir string, out io.Writer) error {
	path := filepath.Join(dir, "SKILL.md")
	have, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		fmt.Fprintf(out, "no rex-plan skill at %s\n", path)
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.Contains(have, []byte(marker)) {
		return fmt.Errorf("%s wasn't written by Rex; leaving it", path)
	}
	if err := os.Remove(path); err != nil {
		return err
	}
	_ = os.Remove(dir) // only if empty
	fmt.Fprintf(out, "removed the rex-plan skill from %s\n", path)
	return nil
}
