// harnessStatus is one harness's row of feed health, read from home.
func harnessStatus(t *testing.T, name string) HarnessStatus {
	t.Helper()
	for _, s := range HarnessStatusesFor("") {
		if s.Name == name {
			return s
		}
	}
	t.Fatalf("%s not registered", name)
	return HarnessStatus{}
}

// docs/ux.md §7a, §10: feed health says whether each wired harness hands
// its agent the pin. A Cursor install from before sessionStart still does
// on prompts, but is partial until the install runs again; an OpenCode
// plugin from before the pin is wired but old, and hands over nothing.
func TestHarnessStatusSaysWhetherThePinGoes(t *testing.T) {
	home := cursorHome(t)
	t.Setenv("XDG_CONFIG_HOME", "")
	os.MkdirAll(filepath.Join(home, ".cursor"), 0o755)
	if s := harnessStatus(t, "cursor"); s.Wired || s.Partial || s.Sends() || s.Caveat == "" {
		t.Fatalf("present, not wired: %#v", s)
	}
	if err := InstallHarness("cursor", io.Discard); err != nil {
		t.Fatal(err)
	}
	if s := harnessStatus(t, "cursor"); !s.Wired || s.Partial || s.Old || !s.Sends() {
		t.Fatalf("installed: %#v", s)
	}
	// An older install: the same hooks, no sessionStart entry.
	path := filepath.Join(home, ".cursor", "hooks.json")
	hooks := readHooks(t, path)["hooks"].(map[string]any)
	if _, ok := hooks["sessionStart"]; !ok {
		t.Fatal("setup: the install registers sessionStart")
	}
	data, _ := os.ReadFile(path)
	start := bytes.Index(data, []byte(`"sessionStart"`))
	end := bytes.Index(data[start:], []byte("],")) + start + len("],")
	os.WriteFile(path, append(append([]byte(nil), data[:start]...), data[end:]...), 0o644)
	if _, ok := readHooks(t, path)["hooks"].(map[string]any)["sessionStart"]; ok {
		t.Fatalf("setup: sessionStart removed\n%s", data)
	}
	if s := harnessStatus(t, "cursor"); !s.Wired || !s.Partial || !s.Sends() {
		t.Fatalf("an install without sessionStart is wired, partial, and still sends on prompts: %#v", s)
	}
	if err := InstallHarness("cursor", io.Discard); err != nil {
		t.Fatal(err)
	}
	if s := harnessStatus(t, "cursor"); !s.Wired || s.Partial {
		t.Fatalf("rerunning the install adds it back: %#v", s)
	}

	plugin := filepath.Join(home, ".config", "opencode", "plugins", "rex.js")
	os.MkdirAll(filepath.Dir(plugin), 0o755)
	os.WriteFile(plugin, []byte("// generated by rex — safe to delete\nexport const RexPlugin = async () => ({})\n"), 0o644)
	if s := harnessStatus(t, "opencode"); !s.Wired || !s.Old || s.Sends() {
		t.Fatalf("an old plugin is wired, old, and sends nothing: %#v", s)
	}
	if err := InstallHarness("opencode", io.Discard); err != nil {
		t.Fatal(err)
	}
	if s := harnessStatus(t, "opencode"); !s.Wired || s.Old || !s.Sends() {
		t.Fatalf("installing again makes it plugin v2: %#v", s)
	}
	for _, s := range []HarnessStatus{{Here: true, Prompts: true}, {Wired: true, Prompts: true}} {
		if !s.Sends() {
			t.Errorf("%#v sends the pin", s)
		}
	}
	for _, s := range []HarnessStatus{{Present: true}, {}, {Wired: true, Prompts: true, Old: true}, {Wired: true}, {Here: true}} {
		if s.Sends() {
			t.Errorf("%#v sends nothing", s)
		}
	}
}

// docs/ux.md §7a: Cursor builds before 3.20 ignore the note on a prompt,
// so its event never says it carried it; every other reply is read.
func TestNoteRead(t *testing.T) {
	prompt := func(v any) map[string]any {
		p := map[string]any{"hook_event_name": "beforeSubmitPrompt"}
		if v != nil {
			p["cursor_version"] = v
		}
		return p
	}
	for v, want := range map[any]bool{
		"3.20.17": true, "3.20": true, "v3.21.0": true, "4.0.1": true, "2026.10.3": true, "3.20-nightly": true, "1999.1": true,
		"3.2.11": false, "3.19.9": false, "1.7.0": false, "3.1": false,
		"2026.10.21": true, "2027.01.02": true, "2026.9.30": false, "2026.09.30": false, "2025.08.25": false, "2000.1": false,
		"": true, "garbage": true, "3": true, nil: true, 3.2: false,
	} {
		if got := NoteRead(prompt(v), "cursor", "beforeSubmitPrompt"); got != want {
			t.Errorf("cursor %v: %v, want %v", v, got, want)
		}
	}
	old := prompt("3.2.11")
	if !NoteRead(old, "cursor", "sessionStart") || !NoteRead(old, "claude", "UserPromptSubmit") || !NoteRead(old, "codex", "UserPromptSubmit") || !NoteRead(old, "opencode", "context") {
		t.Error("sessionStart's note is documented, and no other harness has a build that drops it")
	}
}

// docs/ux.md §7a: the event that carries a note looked up from
// $CURSOR_PROJECT_DIR, its payload naming no folder, comes from there; a
// payload's own folder always wins.
func TestPinOrigin(t *testing.T) {
	dir := t.TempDir()
	if got := PinOrigin(map[string]any{"workspace_roots": []any{}}, dir); len(got) != 1 || got["roots"].([]any)[0] != dir {
		t.Fatalf("no folder of its own: %#v", got)
	}
	if got := PinOrigin(map[string]any{"workspace_roots": []any{"relative"}}, dir); got == nil {
		t.Fatal("a relative root is no origin")
	}
	for _, p := range []map[string]any{{"cwd": dir}, {"workspace_roots": []any{dir}}, {"directory": dir}} {
		if got := PinOrigin(p, t.TempDir()); got != nil {
			t.Errorf("%v names its own: %#v", p, got)
		}
	}
	if PinOrigin(map[string]any{}, "relative") != nil || PinOrigin(map[string]any{}, "") != nil {
		t.Error("only an absolute folder is an origin")
	}
}

// docs/ux.md §7a: a prompt with no text that carried the note is still
// recorded, so the send state counts it; with no note it stays out, and
// a session's start never becomes a prompt.
func TestAPromptWithNoTextThatCarriedThePin(t *testing.T) {
	feed := filepath.Join(t.TempDir(), "session.jsonl")
	dir := t.TempDir()
	pin := map[string]any{"pin": "a", "pin_plan": "rex/plans/x.rex.json"}
	stamp := func(int) map[string]any { return pin }
	for _, c := range []struct {
		source  string
		payload map[string]any
	}{
		{"codex", map[string]any{"hook_event_name": "UserPromptSubmit", "prompt": "", "cwd": dir, "turn_id": "t1"}},
		{"claude", map[string]any{"hook_event_name": "UserPromptSubmit", "cwd": dir}},
		{"cursor", map[string]any{"hook_event_name": "beforeSubmitPrompt", "prompt": "  ", "workspace_roots": []any{dir}, "cursor_version": "3.20.1"}},
		{"opencode", map[string]any{"type": "chat.message", "text": "", "cwd": dir, "pin": "a", "pin_plan": "rex/plans/x.rex.json"}},
	} {
		if err := Record([]map[string]any{c.payload}, c.source, feed, nil); err != nil {
			t.Fatal(err)
		}
		if n := len(LastEvents(feed, 100)); n != 0 {
			t.Fatalf("%s: a prompt with no text and no note is not recorded: %d", c.source, n)
		}
	}
	// A folder and a pin each: the same words with the same pin within
	// seconds, from one folder or one with none, are one prompt reported
	// twice (IsDuplicate).
	for i, c := range []struct {
		source  string
		payload map[string]any
	}{
		{"codex", map[string]any{"hook_event_name": "UserPromptSubmit", "prompt": "", "cwd": t.TempDir(), "turn_id": "t1"}},
		{"claude", map[string]any{"hook_event_name": "UserPromptSubmit", "cwd": t.TempDir(), "session_id": "s2"}},
		{"cursor", map[string]any{"hook_event_name": "beforeSubmitPrompt", "prompt": "  ", "workspace_roots": []any{t.TempDir()}, "cursor_version": "3.20.1", "conversation_id": "c3"}},
		{"opencode", map[string]any{"type": "chat.message", "text": "", "cwd": t.TempDir(), "sessionID": "s4"}},
	} {
		dir := ContextFolders(c.payload, c.source)[0]
		pin := map[string]any{"pin": c.source, "pin_plan": "rex/plans/x.rex.json"}
		if err := Record([]map[string]any{c.payload}, c.source, feed, func(int) map[string]any { return pin }); err != nil {
			t.Fatal(err)
		}
		evs := LastEvents(feed, 100)
		if len(evs) != i+1 {
			t.Fatalf("%s: %d events", c.source, len(evs))
		}
		ev := evs[i]
		if ev.Kind != "user" || ev.Text != NoText || ev.Source != c.source || ev.Meta["pin"] != c.source || ev.Meta["pin_plan"] != "rex/plans/x.rex.json" {
			t.Fatalf("%s: %+v", c.source, ev)
		}
		if in, known := NewScope(dir).Owns(ev); !in || !known {
			t.Fatalf("%s: from its own folder: %+v", c.source, ev.Meta)
		}
	}
	n := len(LastEvents(feed, 100))
	for _, c := range []struct {
		source  string
		payload map[string]any
	}{
		{"claude", map[string]any{"hook_event_name": "SessionStart", "source": "compact", "cwd": dir}},
		{"cursor", map[string]any{"hook_event_name": "sessionStart", "workspace_roots": []any{dir}, "cursor_version": "3.20.1"}},
		{"opencode", map[string]any{"type": "context", "cwd": dir}},
	} {
		if err := Record([]map[string]any{c.payload}, c.source, feed, stamp); err != nil {
			t.Fatal(err)
		}
		if got := len(LastEvents(feed, 100)); got != n {
			t.Fatalf("%s: a session's start or the plugin's request is no prompt", c.source)
		}
	}
}

// docs/ux.md §7a, §10: a harness hands over the pin only from a hook on
// an event that does (Claude Code's and Codex's UserPromptSubmit, Cursor's
// beforeSubmitPrompt or sessionStart): wired on the others alone, it
// records the feed and sends nothing, and feed health says to rerun the
// install.
func TestAHookOffThePromptSendsNothing(t *testing.T) {
	home := cursorHome(t)
	t.Setenv("CLAUDE_CONFIG_DIR", "")
	t.Setenv("CODEX_HOME", "")
	for _, dir := range []string{".claude", ".codex", ".cursor"} {
		os.MkdirAll(filepath.Join(home, dir), 0o755)
	}
	for _, name := range []string{"claude", "codex", "cursor"} {
		if err := InstallHarness(name, io.Discard); err != nil {
			t.Fatal(err)
		}
		if s := harnessStatus(t, name); !s.Wired || !s.Prompts || !s.Sends() {
			t.Fatalf("%s installed: %#v", name, s)
		}
	}
	drop := func(path string, events ...string) {
		t.Helper()
		doc := readHooks(t, path)
		hooks := doc["hooks"].(map[string]any)
		for _, e := range events {
			if _, ok := hooks[e]; !ok {
				t.Fatalf("setup: %s has no %s", path, e)
			}
			delete(hooks, e)
		}
		data, _ := json.MarshalIndent(doc, "", "  ")
		os.WriteFile(path, data, 0o644)
	}
	drop(filepath.Join(home, ".claude", "settings.json"), "UserPromptSubmit", "SessionStart")
	drop(filepath.Join(home, ".codex", "hooks.json"), "UserPromptSubmit")
	cursor := filepath.Join(home, ".cursor", "hooks.json")
	drop(cursor, "beforeSubmitPrompt")
	if s := harnessStatus(t, "cursor"); !s.Wired || !s.Prompts || !s.Partial || !s.Sends() {
		t.Fatalf("cursor with sessionStart alone still hands it over, once a chat: %#v", s)
	}
	drop(cursor, "sessionStart")
	for _, name := range []string{"claude", "codex", "cursor"} {
		if s := harnessStatus(t, name); !s.Wired || s.Prompts || s.Sends() {
			t.Errorf("%s off its prompt hook: %#v", name, s)
		}
	}
	for _, name := range []string{"claude", "codex", "cursor"} {
		if err := InstallHarness(name, io.Discard); err != nil {
			t.Fatal(err)
		}
		if s := harnessStatus(t, name); !s.Prompts || s.Partial || !s.Sends() {
			t.Errorf("%s: rerunning the install puts it back: %#v", name, s)
		}
	}
	// Claude Code wired only in a repo's own settings.
	repo := t.TempDir()
	os.Mkdir(filepath.Join(repo, ".git"), 0o755)
	if err := UninstallHarness("claude", io.Discard); err != nil {
		t.Fatal(err)
	}
	if err := InstallClaudeProject(repo, io.Discard); err != nil {
		t.Fatal(err)
	}
	here := func() HarnessStatus {
		for _, s := range HarnessStatusesFor(repo) {
			if s.Name == "claude" {
				return s
			}
		}
		return HarnessStatus{}
	}
	if s := here(); s.Wired || !s.Here || !s.Prompts || !s.Sends() {
		t.Fatalf("for this repo: %#v", s)
	}
	drop(ClaudeProjectSettings(repo), "UserPromptSubmit")
	if s := here(); !s.Here || s.Prompts || s.Sends() {
		t.Fatalf("for this repo, off its prompt hook: %#v", s)
	}
}
