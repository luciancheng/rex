// Package skill holds the rex-plan agent skill, embedded so the binary
// can install it. It is installed only on an explicit
// `rex ingest --install-skill`, so nothing joins an agent's context unasked.
package skill

import (
	"bytes"
	_ "embed"
	"fmt"
	"io"
	"os"
	"path/filepath"
)

//go:embed rex-plan/SKILL.md
var RexPlan []byte

const marker = "<!-- generated by rex"

// Dirs are where the skill goes, so all four agents read it: Codex reads
// skills only from .agents/skills, Claude Code only from .claude/skills
// (or $CLAUDE_CONFIG_DIR/skills), and Cursor and OpenCode from both. With
// project they are the repo's; else they are under home, and a home-based
// one is "" when there is no home folder.
func Dirs(home, repo string, project bool) []string {
	if project {
		return []string{filepath.Join(repo, ".claude", "skills", "rex-plan"), filepath.Join(repo, ".agents", "skills", "rex-plan")}
	}
	claude, agents := "", ""
	if home != "" {
		claude = filepath.Join(home, ".claude", "skills", "rex-plan")
		agents = filepath.Join(home, ".agents", "skills", "rex-plan")
	}
	if dir := os.Getenv("CLAUDE_CONFIG_DIR"); dir != "" {
		claude = filepath.Join(dir, "skills", "rex-plan")
	}
	return []string{claude, agents}
}

// Legacy is ~/.claude/skills/rex-plan while $CLAUDE_CONFIG_DIR moves
// Claude Code's copy elsewhere, else "". Cursor and OpenCode still read
// it, so a copy Rex wrote there is kept up to date and taken out with the
// others; one Rex didn't write is never touched.
func Legacy(home string) string {
	if home == "" || os.Getenv("CLAUDE_CONFIG_DIR") == "" {
		return ""
	}
	if dir := filepath.Join(home, ".claude", "skills", "rex-plan"); dir != Dirs(home, "", false)[0] {
		return dir
	}
	return ""
}

// Ours reports whether dir holds a SKILL.md that Rex wrote.
func Ours(dir string) bool {
	have, err := os.ReadFile(filepath.Join(dir, "SKILL.md"))
	return err == nil && bytes.Contains(have, []byte(marker))
}

// Copy is how Rex's SKILL.md stands in the folders agents read.
type Copy int

const (
	Missing      Copy = iota // in none of them
	Current                  // Rex's copy, and none from an older Rex
	Stale                    // an older Rex's copy in this user's folders
	StaleProject             // an older Rex's copy in this repo's folders
)

// Look finds Rex's SKILL.md in any folder Dirs or Legacy names, for this
// user or this repo. A copy an older Rex wrote (its bytes differ from
// RexPlan) still teaches its workflow, so it is Stale until
// --install-skill replaces it; this user's copies are judged before the
// repo's.
func Look(home, repo string) Copy {
	dirs := Dirs(home, repo, false)
	if dir := Legacy(home); dir != "" {
		dirs = append(dirs, dir)
	}
	mine := len(dirs)
	if repo != "" {
		dirs = append(dirs, Dirs(home, repo, true)...)
	}
	found := Missing
	for i, dir := range dirs {
		if dir == "" {
			continue
		}
		have, err := os.ReadFile(filepath.Join(dir, "SKILL.md"))
		if err != nil || !bytes.Contains(have, []byte(marker)) {
			continue
		}
		switch {
		case bytes.Equal(have, RexPlan):
			found = max(found, Current)
		case i < mine:
			return Stale
		default:
			found = StaleProject
		}
	}
	return found
}

// Install writes SKILL.md into dir. A SKILL.md that Rex didn't write is
// left alone.
func Install(dir string, out io.Writer) error {
	path := filepath.Join(dir, "SKILL.md")
	have, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return err // can't tell whose it is, so it stays
	}
	if err == nil {
		if !bytes.Contains(have, []byte(marker)) {
			return fmt.Errorf("%s exists and Rex didn't write it; move it to install the rex-plan skill", path)
		}
		if bytes.Equal(have, RexPlan) {
			fmt.Fprintf(out, "rex-plan skill already installed at %s\n", path)
			return nil
		}
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".SKILL.md.rex-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(RexPlan); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return err
	}
	fmt.Fprintf(out, "installed the rex-plan skill at %s\n", path)
	return nil
}

// Uninstall removes Rex's SKILL.md and the folder if that leaves it empty.
func Uninstall(dir string, out io.Writer) error {
	path := filepath.Join(dir, "SKILL.md")
	have, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		fmt.Fprintf(out, "no rex-plan skill at %s\n", path)
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.Contains(have, []byte(marker)) {
		return fmt.Errorf("%s wasn't written by Rex; leaving it", path)
	}
	if err := os.Remove(path); err != nil {
		return err
	}
	_ = os.Remove(dir) // only if empty
	fmt.Fprintf(out, "removed the rex-plan skill from %s\n", path)
	return nil
}
